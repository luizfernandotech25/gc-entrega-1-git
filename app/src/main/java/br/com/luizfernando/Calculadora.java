package br.com.luizfernando;

/**
 * Classe responsável por realizar operações matemáticas básicas.
 *
 * @author Luiz Fernando Rodrigues
 * @version 1.0
 */
public class Calculadora {

    /**
     * Soma dois números inteiros.
     *
     * @param a primeiro número inteiro
     * @param b segundo número inteiro
     * @return resultado da soma de a e b
     */
    public int somar(int a, int b) {
        return a + b;
    }

    /**
     * Multiplica dois números inteiros.
     *
     * @param a primeiro número inteiro
     * @param b segundo número inteiro
     * @return resultado da multiplicação de a e b
     */
    public int multiplicar(int a, int b) {
        return a * b;
    }
}
